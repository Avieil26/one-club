import assert from 'node:assert/strict';
import { loadRepositoryModule } from './load-player-catalogue.mjs';
const {isPublicPath}=loadRepositoryModule('lib/siteAccess.ts');
for(const path of ['/','/market','/market/icon-ronaldo','/grounds','/sbc','/sbc/sbc-potm-ferran','/sbc/calculator','/career','/career/ch-leeds-title','/ultimate','/games/grid','/settings']) assert(isPublicPath(path),path);
for(const path of ['/admin/retention','/profile','/squad','/grounds/new','/grounds/chat/person','/sbc/build/challenge','/sbc/upload/challenge','/career/submit/challenge','/ultimate/new','/career/journeys/new','//evil.invalid','https://evil.invalid','/sbc/../new']) assert(!isPublicPath(path),path);
const {filterSbcs,endsSoon,newlyReleased}=loadRepositoryModule('lib/sbcBrowse.ts');
const {catalogChallenge}=loadRepositoryModule('lib/sbcCatalog.ts');
const ferran=catalogChallenge('sbc-potm-ferran');
const pack=catalogChallenge('sbc-mm-juventus-lazio-20261015');
const upgrade=catalogChallenge('sbc-upgrade-83x2-20261020');
const now=Date.parse('2026-10-20T20:00:00Z');
assert.equal(filterSbcs([ferran,pack,upgrade],'ferran','all',now)[0].id,ferran.id);
assert.equal(filterSbcs([ferran,pack,upgrade],'','players',now).length,1);
assert.equal(filterSbcs([ferran,pack,upgrade],'','packs',now).length,1);
assert.equal(filterSbcs([ferran,pack,upgrade],'','upgrades',now).length,1);
assert.equal(filterSbcs([ferran,pack,upgrade],'nonsense','all',now).length,0);
assert(!endsSoon({...ferran,endsAt:new Date(now).toISOString()},now));
assert(endsSoon({...ferran,endsAt:new Date(now+86400000).toISOString()},now));
assert(!endsSoon({...ferran,endsAt:new Date(now+86400001).toISOString()},now));
assert(!newlyReleased({...ferran,createdAt:new Date(now+1).toISOString()},now));
assert(newlyReleased({...ferran,createdAt:new Date(now-1000).toISOString()},now));
console.log('Public browsing/private action boundaries, bilingual SBC search, reward filters and release/deadline boundaries passed.');
